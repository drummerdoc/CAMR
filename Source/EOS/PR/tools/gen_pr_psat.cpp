// gen_pr_psat: tabulate the Peng-Robinson coexistence pressure of the CAMR
// CO2 fluid (hem::Psat, equal fugacities) as a cubic Hermite spline on
// knots uniform in theta = sqrt(1 - T/Tc), T in [T_triple, Tc], and write
// ../pr_psat_tab.H.  Same layout as EOS/GERG/gerg_co2_sat.H.  Run from
// this directory:
//   g++ -O2 -std=c++17 -DHEM_NO_AMREX -I.. -o gen_pr_psat gen_pr_psat.cpp && ./gen_pr_psat
// The fluid constants must equal EOS::co2_fluid() in pr_base.H.
#ifndef HEM_NO_AMREX
#define HEM_NO_AMREX
#endif
#include "hem_pr_state.H"
#include <cstdio>
#include <cmath>
#include <vector>
int main() {
    const hem::PRFluid f = hem::PRFluid::make(304.13, 7.3773e6, 0.22394, 0.04401,
        2.35681300E+00, 8.98412990E-03, -7.12206320E-06, 2.45730071E-09, -1.42885166E-13, 0.0);
    const double Tc = 304.13, Tt = 216.592, T_hi = Tc - 0.5;   // the last 0.5 K is clamped to Pc (the Newton loses digits there)
    const int N = 128;
    const double th_lo = std::sqrt(1.0 - T_hi / Tc), th_hi = std::sqrt(1.0 - Tt / Tc);
    const double dth = (th_hi - th_lo) / (N - 1);
    std::vector<double> T(N), P(N), dP(N);
    for (int i = 0; i < N; ++i) {
        const double th = th_lo + i * dth;
        T[i] = Tc * (1.0 - th * th);
        P[i] = hem::Psat(f.pr, T[i]);
        const double h = 1.0e-3;
        dP[i] = (hem::Psat(f.pr, T[i] + h, P[i]) - hem::Psat(f.pr, T[i] - h, P[i])) / (2 * h);
    }
    // Hermite in theta: y'(theta) = dP/dT * dT/dtheta = dP/dT * (-2 Tc theta)
    std::vector<double> yp(N);
    for (int i = 0; i < N; ++i) yp[i] = dP[i] * (-2.0 * Tc * (th_lo + i * dth));
    // accuracy check at knot midpoints
    double err = 0.0, worst_T = 0.0;
    for (int i = 0; i + 1 < N; ++i) {
        const double t = 0.5, t2 = t*t, t3 = t2*t, h = dth;
        const double s = P[i]*(2*t3-3*t2+1) + yp[i]*h*(t3-2*t2+t) + P[i+1]*(-2*t3+3*t2) + yp[i+1]*h*(t3-t2);
        const double th = th_lo + (i + 0.5) * dth, Tm = Tc * (1.0 - th * th);
        const double ex = hem::Psat(f.pr, Tm);
        if (std::fabs(s - ex) / ex > err) { err = std::fabs(s - ex) / ex; worst_T = Tm; }
    }
    FILE* o = std::fopen("../pr_psat_tab.H", "w");
    std::fprintf(o, "#ifndef PR_PSAT_TAB_H\n#define PR_PSAT_TAB_H\n");
    std::fprintf(o, "// GENERATED by tools/gen_pr_psat.cpp -- do not edit.  Peng-Robinson coexistence\n"
                    "// pressure of the CAMR CO2 fluid (equal fugacities, hem::Psat) as a cubic Hermite\n"
                    "// spline on %d knots uniform in theta = sqrt(1 - T/Tc), T in [T_triple, Tc - 0.5 K]; above, Pc.\n"
                    "// Max relative error at knot midpoints: %.2e.  This is the EOS's own saturation\n"
                    "// curve, the one its two-phase states are built on (docs/DESIGN_DECISIONS.md R-16).\n", N, err);
    std::fprintf(o, "namespace pr_psat {\nconstexpr int    NPS   = %d;\nconstexpr double TC    = %.17g;\n"
                    "constexpr double TH_LO = %.17g;\nconstexpr double TH_HI = %.17g;\nconstexpr double DTH   = %.17g;\n"
                    "constexpr double P_TRIPLE = %.17g;   // coexistence pressure at T_triple\n", N, Tc, th_lo, th_hi, dth, P[N-1]);
    std::fprintf(o, "constexpr double PS[NPS] = {\n");
    for (int i = 0; i < N; ++i) std::fprintf(o, "    %.17g,%s", P[i], (i % 3 == 2 || i == N-1) ? "\n" : "");
    std::fprintf(o, "};\nconstexpr double PSP[NPS] = {\n");
    for (int i = 0; i < N; ++i) std::fprintf(o, "    %.17g,%s", yp[i], (i % 3 == 2 || i == N-1) ? "\n" : "");
    std::fprintf(o, "};\n} // namespace pr_psat\n#endif\n");
    std::fclose(o);
    std::printf("wrote ../pr_psat_tab.H: %d knots, max midpoint rel error %.3e at T=%.3f; P(T_triple)=%.6g P(280)=%.6g\n", N, err, worst_T, P[N-1], hem::Psat(f.pr, 280.0));
    return 0;
}
