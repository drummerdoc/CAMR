  // Branch selector (host runtime): CAMR.eos_table_branch = 1 (default) makes
  // the branch-locked EOS calls use the metastable liquid/vapor tables (needed
  // for two-phase / B-cases); 0 makes them use the auto-detect table (fine for
  // single-phase A/C, cheaper reasoning).  All three tables are always built.
  inline bool mlpx2_table_branch()
  {
      static const bool b = []() {
          int v = 1; amrex::ParmParse pp("CAMR");
          pp.query("eos_table_branch", v); return v != 0;
      }();
      return b;
  }
